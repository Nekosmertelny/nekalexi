def normalize_cefr_level(raw: object) -> CefrLevel:
    upper = str(raw or "").strip().upper()
    if upper in ("A1", "A2", "B1", "B2", "C1"):
        return upper  # type: ignore[return-value]
    return "A2"


def get_curated_decks_for_level(level: CefrLevel) -> list[CuratedDeckSpec]:
    exact = [d for d in CURATED_DECKS_CATALOG if d["cefrLevel"] == level]
    return exact if exact else [CURATED_DECKS_CATALOG[1]]
